"""Train once per seed, select on validation only, evaluate held-out combinations."""
import copy
import hashlib
import itertools
import json
import platform
import random
import time

import torch
from torch import nn

from model import ROOT, QUESTIONS, OPTIONS, HEADS, InterviewCNN, encode, rule_labels, propose

EPOCHS = 200
SEEDS = [7, 17, 29]


def metrics(outputs, labels, indices):
    correct = torch.stack([outputs[k].argmax(1) == labels[k][indices] for k in HEADS])
    return {
        "exact_all_heads": correct.all(0).float().mean().item(),
        "per_head": {k: correct[i].float().mean().item() for i, k in enumerate(HEADS)},
    }


def main():
    torch.set_num_threads(1)
    torch.use_deterministic_algorithms(True)
    rows = [dict(zip(QUESTIONS, values)) for values in itertools.product(*(OPTIONS[k] for k in QUESTIONS))]
    x = encode(rows)
    labels = {k: torch.tensor([HEADS[k].index(rule_labels(row)[k]) for row in rows]) for k in HEADS}
    indices = list(range(len(rows)))
    random.Random(20261121).shuffle(indices)
    split = {"train": indices[:154], "validation": indices[154:205], "test": indices[205:]}
    assert set(split["train"]).isdisjoint(split["test"])
    assert set(split["validation"]).isdisjoint(split["test"])
    results = ROOT / "results"
    results.mkdir(exist_ok=True)
    report = {
        "data": "Synthetic authored policy labels; no human participants or usability outcomes.",
        "environment": {"python": platform.python_version(), "torch": torch.__version__, "device": "cpu"},
        "interview_sha256": hashlib.sha256((ROOT / "interview.json").read_bytes()).hexdigest(),
        "split_seed": 20261121, "split_indices": split,
        "sample_counts": {k: len(v) for k, v in split.items()},
        "training": {"epochs": EPOCHS, "optimizer": "Adam", "learning_rate": 0.01,
                     "batch": "full training split", "selection": "lowest validation cross-entropy"},
        "runs": [], "samples": [],
    }
    test = split["test"]
    majority = {k: torch.nn.functional.one_hot(labels[k][split["train"]].bincount().argmax().repeat(len(test)), len(HEADS[k])).float() for k in HEADS}
    report["majority_baseline"] = metrics(majority, labels, test)
    report["rules_baseline_exact"] = 1.0  # Labels are generated by these rules, by construction.
    for seed in SEEDS:
        torch.manual_seed(seed)
        model = InterviewCNN()
        optimizer = torch.optim.Adam(model.parameters(), lr=0.01)
        best_loss, best_state, best_epoch = float("inf"), None, None
        history = []
        started = time.perf_counter()
        for epoch in range(EPOCHS):
            model.train()
            optimizer.zero_grad()
            outputs = model(x[split["train"]])
            loss = sum(nn.functional.cross_entropy(outputs[k], labels[k][split["train"]]) for k in HEADS)
            loss.backward()
            optimizer.step()
            model.eval()
            with torch.no_grad():
                val = model(x[split["validation"]])
                val_loss = sum(nn.functional.cross_entropy(val[k], labels[k][split["validation"]]) for k in HEADS).item()
            if val_loss < best_loss:
                best_loss, best_state, best_epoch = val_loss, copy.deepcopy(model.state_dict()), epoch + 1
            if epoch % 20 == 0 or epoch == EPOCHS - 1:
                history.append({"epoch": epoch + 1, "training_loss": loss.item(), "validation_loss": val_loss})
        model.load_state_dict(best_state)
        model.eval()
        with torch.no_grad():
            raw = model(x[test])
        run = {"seed": seed, "selected_epoch": best_epoch, "validation_loss": best_loss,
               "test": metrics(raw, labels, test), "loss_history": history,
               "training_seconds": time.perf_counter() - started}
        predictions = {k: raw[k].argmax(1).tolist() for k in HEADS}
        run["failures"] = [{"answers": rows[idx], "expected": rule_labels(rows[idx]),
                            "predicted": {k: HEADS[k][predictions[k][j]] for k in HEADS}}
                           for j, idx in enumerate(test)
                           if any(predictions[k][j] != labels[k][idx] for k in HEADS)]
        report["runs"].append(run)
        # First predeclared seed is the demonstrator; never select by test performance.
        if seed == SEEDS[0]:
            torch.save(model.state_dict(), results / "model.pt")
            report["parameter_count"] = sum(p.numel() for p in model.parameters())
            for idx in test[:3]:
                with torch.no_grad():
                    output, trace = model(x[idx:idx + 1], trace=True)
                proposal, decision = propose(rows[idx], model)
                report["samples"].append({
                    "answers": rows[idx], "expected": rule_labels(rows[idx]),
                    "layers": {k: {"shape": list(v.shape), "minimum": v.min().item(),
                                    "maximum": v.max().item(), "values": v[0].tolist()} for k, v in trace.items()},
                    "heads": {k: {"predicted": HEADS[k][int(v.argmax(1))],
                                   "probabilities_uncalibrated": dict(zip(HEADS[k], v.softmax(1)[0].tolist()))}
                              for k, v in output.items()},
                    "proposal": proposal, "decision": decision,
                })
            fixtures = [{"answers": row, "proposal": propose(row, model)[0]} for row in rows]
            (results / "proposals.json").write_text(json.dumps(fixtures, ensure_ascii=False, indent=2) + "\n")
    (results / "report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({"counts": report["sample_counts"], "parameters": report["parameter_count"],
                      "test": [r["test"] for r in report["runs"]]}, indent=2))


if __name__ == "__main__":
    main()
